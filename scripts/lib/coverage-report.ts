/**
 * Pure builder for `content/COVERAGE.md`. Deliberately has no time-varying
 * inputs (no timestamps) — its output is a pure function of the import
 * results, so re-running the importer with unchanged upstream data
 * produces a byte-identical file.
 */

export interface VersionCoverageStat {
  layer: "source" | "commentary";
  versionId: string;
  chaptersTotal: number;
  chaptersWithText: number;
  segments: number;
  /** Chapter ids that were attempted for this version but ended up with zero segments. */
  emptyChapterIds: string[];
}

export interface PartCoverage {
  partId: string;
  partTitle: string;
  stats: VersionCoverageStat[];
  warnings: string[];
}

const table = (stats: VersionCoverageStat[]): string => {
  const header =
    "| Layer | Version | Chapters w/ text | Chapters total | Segments |";
  const divider = "| --- | --- | --- | --- | --- |";
  const rows = stats.map(
    (s) =>
      `| ${s.layer} | ${s.versionId} | ${s.chaptersWithText} | ${s.chaptersTotal} | ${s.segments} |`,
  );
  return [header, divider, ...rows].join("\n");
};

const emptyChapterNotes = (stats: VersionCoverageStat[]): string[] =>
  stats
    .filter((s) => s.emptyChapterIds.length > 0)
    .map(
      (s) =>
        `- **${s.layer}/${s.versionId}**: no text for ${s.emptyChapterIds.length} chapter(s) — ${s.emptyChapterIds.join(", ")}`,
    );

export const buildCoverageMarkdown = (parts: PartCoverage[]): string => {
  const sections = parts.map((part) => {
    const lines = [
      `## ${part.partTitle} (\`${part.partId}\`)`,
      "",
      table(part.stats),
    ];

    const notes = emptyChapterNotes(part.stats);
    if (notes.length > 0) {
      lines.push("", "**Empty-version chapters:**", ...notes);
    }

    if (part.warnings.length > 0) {
      lines.push("", "**Warnings:**", ...part.warnings.map((w) => `- ${w}`));
    }

    return lines.join("\n");
  });

  return [
    "# Import coverage",
    "",
    "Generated by `pnpm import:sefaria`. Per part × layer × version: how many",
    "of the part's resolved chapters ended up with text in that version, and",
    "how many total segments/commentary items were written.",
    "",
    "## Not written vs. not yet imported",
    "",
    "An empty row below is a gap in what has been *imported*. Two absences in",
    "this corpus are not gaps at all — the text does not exist to import:",
    "",
    "- **Histaklut Pnimit (Inner Observation) — parts 5, 11, 14, 15 and 16",
    "  (2,193 chapters): not written.** Baal HaSulam wrote an Inner",
    "  Observation for eleven of the sixteen parts and none for these five.",
    "  Three independent sources agree: Sefaria's index carries a Histaklut",
    "  node for the other eleven Sections only; his own 262 Hebrew",
    '  cross-references to `הסת"פ` / `הסתכלות פנימית` never point at these',
    "  five parts, and the single Inner Observation reference inside each of",
    "  them sends the reader to *another* part's; and Bnei Baruch's published",
    "  contents listing omits Inner Observation for exactly these five. The",
    "  reader states this as a fact about the work, not as pending work",
    "  (`reader.innerObservationNeverWritten`).",
    "- **Ohr Pnimi (Inner Light) — everything outside the 25 digitized",
    "  chapters: not yet imported.** This one *is* a digitization gap and",
    "  behaves like one — parts 1-4 and then nothing, a stopped tail rather",
    '  than holes — so its copy keeps the "yet"',
    "  (`reader.innerLightAbsent`).",
    "",
    ...sections,
    "",
  ].join("\n");
};
